// @vitest-environment jsdom
import { render, screen, within } from "@testing-library/react";
import type { ConcernRollup } from "brief-core/types";
import { describe, expect, it } from "vitest";

import type { Brief } from "../../../../../model/types";
import { buildBriefViewModel } from "../../../../../model/utils/view-model";
import { briefFixture } from "../../../../../test-utils/fixtures";
import { computeConcernShares } from "../utils";
import { StatsCard } from ".";

const brief: Brief = {
  ...briefFixture,
  commitRange: { base: "basebase1111", head: "headhead2222", commitCount: 3 },
  generation: { provider: "anthropic", model: "m-1", effort: "high" },
};

const TWO_CONCERNS: ConcernRollup[] = [
  { concern: "implementation", added: 40, deleted: 10 },
  { concern: "test", added: 30, deleted: 0 },
];

function renderCard(rollup: ConcernRollup[], subject: Brief = brief) {
  const model = buildBriefViewModel(subject);
  return render(
    <StatsCard
      brief={subject}
      model={model}
      shares={computeConcernShares(rollup, { added: 20, deleted: 0 })}
    />,
  );
}

describe("StatsCard", () => {
  it("shows how the brief was generated and the span it covers", () => {
    renderCard(TWO_CONCERNS);

    expect(
      screen.getByRole("heading", { level: 2, name: "Generated by" }),
    ).toBeTruthy();
    expect(document.querySelector("[data-provider-badge]")).not.toBeNull();
    expect(screen.getByTestId("coverage-line").textContent).toBe(
      "Covers basebas..headhea · 3 commits",
    );
  });

  it("lists the Split in vocabulary order with the remainder last", () => {
    renderCard(TWO_CONCERNS);

    const rows = within(screen.getByTestId("split-rows")).getAllByRole(
      "listitem",
    );
    expect(rows.map((row) => row.getAttribute("data-concern"))).toEqual([
      "implementation",
      "test",
      null,
    ]);
    expect(rows[0]?.textContent).toContain("50%");
    expect(rows[2]?.textContent).toContain("Unattributed");
  });

  it("drops the Split below two concerns", () => {
    renderCard([{ concern: "implementation", added: 40, deleted: 10 }]);

    expect(screen.queryByRole("heading", { name: "Split" })).toBeNull();
    expect(screen.queryByTestId("split-rows")).toBeNull();
  });

  it("leaves the coverage line off a delta", () => {
    renderCard(TWO_CONCERNS, { ...brief, artifactKind: "delta" });

    expect(screen.queryByTestId("coverage-line")).toBeNull();
  });
});
