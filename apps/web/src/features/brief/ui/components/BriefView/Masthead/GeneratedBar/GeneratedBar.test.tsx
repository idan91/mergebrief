// @vitest-environment jsdom
import { render, screen } from "@testing-library/react";
import { describe, expect, it } from "vitest";

import type { Brief } from "../../../../../model/types";
import { buildBriefViewModel } from "../../../../../model/utils/view-model";
import { briefFixture } from "../../../../../test-utils/fixtures";
import { GeneratedBar } from ".";

const brief: Brief = {
  ...briefFixture,
  commitRange: { base: "basebase1111", head: "headhead2222", commitCount: 1 },
  generation: { provider: "anthropic", model: "m-1", effort: "high" },
};

describe("GeneratedBar", () => {
  it("heads the provenance with its title and closes on the span", () => {
    render(<GeneratedBar brief={brief} model={buildBriefViewModel(brief)} />);

    expect(
      screen.getByRole("heading", { level: 2, name: "Generated by" }),
    ).toBeTruthy();
    expect(document.querySelector("[data-provider-badge]")).not.toBeNull();
    expect(screen.getByTestId("coverage-line").textContent).toBe(
      "Covers basebas..headhea · 1 commit",
    );
  });
});
