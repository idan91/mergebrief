import {
  ClassicFieldReads,
  LockfileReadFailures,
  type ClassicFieldRead,
  type LockfileEntry,
  type LockfileRead,
  type PackageKey,
} from "./types";
import {
  failRead,
  readFetchIdentity,
  REGISTRY_HOST,
  WORKSPACE_HOST,
  splitPackageKey,
} from "./utils";
import { readYamlLockfile, type YamlLockfileShape } from "./yaml";

const CLASSIC_MARKER_WINDOW = 512;
/** The marker as a whole line: `v10` and `v2` are not classic. */
const CLASSIC_MARKER_LINE = /^# yarn lockfile v1\r?$/m;
/** Berry's legacy marker, tried at one comment line's start. */
const BERRY_LEGACY_MARKER = /#\s+yarn\s+lockfile\s+v1\r?\n/iy;
/** What `.` matches: anything but a line terminator. */
const LINE_BODY = /[^\n\r\u2028\u2029]*/y;
/**
 * The header comments yarn's writer emits. Any other comment can make yarn
 * 1's parser throw (`yarn lockfile v2`) and fall back to reading YAML.
 */
const CLASSIC_HEADER_COMMENTS: ReadonlySet<string> = new Set([
  "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.",
  "# yarn lockfile v1",
]);
const CLASSIC_VERSION_COMMENT = /^# (?:yarn|node) v\d+\.\d+\.\d+$/;
const METADATA_KEY = "__metadata";
const BERRY_BINDINGS_SEPARATOR = "::";
const BERRY_ARCHIVE_BINDING = "__archiveUrl";
/** `npm:<version>`: the package itself from the configured registry. */
const PLAIN_NPM_REFERENCE = /^npm:[^:?#@]+$/;
/** `patch:<inner resolution, URL-encoded>#<patch>`: fetched as the inner resolution, then patched locally. */
const PATCH_PROTOCOL = "patch:";
const PATCH_SEPARATOR = "#";
const WORKSPACE_PROTOCOL = "workspace:";
/** The range of a descriptor that aliases another package: `npm:<name>@<range>`. */
const NPM_ALIAS_PREFIX = "npm:";
const METADATA_LINE = `${METADATA_KEY}:`;
/** Berry writes one document: `__metadata`, then one key per package locator, each naming a package. */
const BERRY_SHAPE: YamlLockfileShape = {
  maxDocuments: 1,
  isTopKey: (key) => key === METADATA_KEY || splitPackageKey(key) !== undefined,
};
const DESCRIPTOR_SEPARATOR = ",";
/** The most descriptors one key of ten large public yarn lockfiles lists is 22. */
const MAX_DESCRIPTORS_PER_KEY = 128;
/**
 * One classic token exactly as yarn's writer emits it: quoted, non-empty,
 * with no escape or control character, or bare from a letter, never
 * `true`/`false`. A bare token may hold `#` (`foo@acme/foo#v1.0.0`): yarn
 * reads a comment only at a token's start. Anything else can
 * make yarn's own parser throw and fall back to reading the file as YAML.
 */
const TOKEN = String.raw`(?:"[^"\\\x00-\x1f\x7f]+"|(?!true|false)[a-zA-Z][^\s"':,\\]*)`;
/** A value token: yarn writes an empty string quoted, as `uid ""` on a `link:` entry. */
const VALUE_TOKEN = String.raw`(?:""|${TOKEN})`;
const BARE_TOKEN = new RegExp(`^${TOKEN}$`);
const LINE_BREAK = /\r?\n/;
const NESTED_LINE = /^ {4}\S/;
/** A nested classic line: two tokens, as under `dependencies:`. */
const NESTED_FIELD = new RegExp(`^ {4}${TOKEN} ${VALUE_TOKEN}$`);
/** yarn's tokenizer ends a line at a lone carriage return too, which a `\n` split misses. */
const LONE_CARRIAGE_RETURN = /\r(?!\n)/;
const TRAILING_CARRIAGE_RETURN = /\r$/;
/** Every field yarn of either dialect fetches from, so one the other ignores still counts. */
const SOURCE_FIELDS = ["resolved", "integrity", "resolution", "checksum"];
/** A range yarn 1 hands an exotic resolver (path, URL, git, alias), not a registry range. */
const EXOTIC_RANGE = /[:/]|^\./;
/** A range yarn 1 copies or links from disk, reading nothing of the entry's `resolved`; a drive letter on Windows. */
const LOCAL_RANGE = /^(?:file:|link:|\.|~\/|\/|[A-Za-z]:\/)/;
/** A classic field line: one key token, then one value token or a block opener `:`. */
const CLASSIC_FIELD = new RegExp(`^ {2}(${TOKEN})(?: (${VALUE_TOKEN})|:)$`);

const BerryEntrySchema = z.object({
  version: z.string(),
  resolved: z.string().optional(),
  integrity: z.string().optional(),
  resolution: z.string().optional(),
  checksum: z.string().optional(),
});

interface ClassicEntry {
  descriptors: string[];
  fields: Map<string, string>;
}

function readQuoted(token: string): string | undefined {
  if (!token.startsWith('"')) {
    return token;
  }
  try {
    const value: unknown = JSON.parse(token);
    return typeof value === "string" ? value : undefined;
  } catch {
    return undefined;
  }
}

/** Splits at every comma outside a quoted token, as yarn's tokenizer does. */
function splitUnquotedCommas(text: string): string[] {
  const tokens: string[] = [];
  let start = 0;
  let quoted = false;
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    if (quoted && char === "\\") {
      index += 1;
    } else if (char === '"') {
      quoted = !quoted;
    } else if (char === DESCRIPTOR_SEPARATOR && !quoted) {
      tokens.push(text.slice(start, index));
      start = index + 1;
    }
  }
  tokens.push(text.slice(start));
  return tokens;
}

/** Every descriptor of a classic key line, or nothing for a token yarn never writes. */
function readClassicDescriptors(keyText: string): string[] | undefined {
  const tokens = splitUnquotedCommas(keyText);
  if (tokens.length > MAX_DESCRIPTORS_PER_KEY) {
    return undefined;
  }
  const descriptors: string[] = [];
  for (const [position, raw] of tokens.entries()) {
    // yarn writes `key, key:`: one space after each comma and nowhere else.
    const token = position === 0 ? raw : raw.slice(1);
    const spaced = position === 0 || raw.startsWith(" ");
    const readable = spaced && BARE_TOKEN.test(token);
    const descriptor = readable ? readQuoted(token) : undefined;
    const usable =
      descriptor !== undefined &&
      descriptor !== "" &&
      !descriptor.includes(DESCRIPTOR_SEPARATOR);
    if (!usable) {
      return undefined;
    }
    descriptors.push(descriptor);
  }
  return descriptors;
}

/** Every descriptor of a berry key, split at each comma as berry does. */
function readBerryDescriptors(key: string): string[] | undefined {
  const descriptors = key
    .split(DESCRIPTOR_SEPARATOR)
    .map((token) => token.trim());
  return descriptors.includes("") ? undefined : descriptors;
}

/** The package berry's `resolution` names, when it gives one. */
function readResolvedName(resolution: string | undefined): string | undefined {
  return resolution === undefined
    ? undefined
    : splitPackageKey(resolution)?.name;
}

/** The package a yarn entry fetches, and every name it installs under. */
interface ClaimedNames {
  fetched: string;
  installed: string[];
}

/** The package a descriptor installs: the one `npm:<name>@<range>` aliases, else its own name. */
function readDescriptorTarget(key: PackageKey): string {
  const aliased = key.version.startsWith(NPM_ALIAS_PREFIX)
    ? splitPackageKey(key.version.slice(NPM_ALIAS_PREFIX.length))
    : undefined;
  return aliased?.name ?? key.name;
}

/**
 * The names a yarn key installs. Both dialects merge every descriptor that
 * resolves to one package into one key, aliases included:
 * `string-width-cjs@npm:string-width@^4, string-width@^4` installs
 * `string-width` and, as its alias, `string-width-cjs`. Every descriptor
 * must install the same package, berry's `resolution` naming it when
 * given; a descriptor another key already claimed makes the key ambiguous.
 */
function claimNames(
  descriptors: readonly string[],
  resolvedName: string | undefined,
  seen: Set<string>,
): ClaimedNames | undefined {
  const installed = new Set<string>();
  const targets = new Set<string>();
  for (const descriptor of new Set(descriptors)) {
    const key = splitPackageKey(descriptor);
    if (key === undefined || seen.has(descriptor)) {
      return undefined;
    }
    seen.add(descriptor);
    installed.add(key.name);
    targets.add(readDescriptorTarget(key));
  }
  const [target] = targets;
  const fetched = resolvedName ?? target;
  const agreed = targets.size === 1 && target === fetched;
  const readsOneTarget = agreed && fetched !== undefined;
  return readsOneTarget ? { fetched, installed: [...installed] } : undefined;
}

function readSource(readField: (field: string) => string | undefined): string {
  return SOURCE_FIELDS.map((field) => readField(field) ?? "").join(" ");
}

/** The reference a berry `resolution` field names: `npm:1.2.3`, `workspace:packages/a`. */
function readBerryReference(
  readField: (field: string) => string | undefined,
): string | undefined {
  const resolution = readField("resolution");
  return resolution === undefined
    ? undefined
    : splitPackageKey(resolution)?.version;
}

/** One installed name's entry; every name of one key shares its source and host. */
function toEntry(
  name: string,
  version: string,
  source: string,
  host: string | undefined,
): LockfileEntry {
  const entry: LockfileEntry = { name, version, source };
  if (host !== undefined) {
    entry.host = host;
  }
  return entry;
}

/** Classic yarn fetches from `resolved` and nothing else. */
function readClassicHost(
  readField: (field: string) => string | undefined,
  pkg: PackageKey,
): string | undefined {
  const resolved = readField("resolved");
  return resolved === undefined ? undefined : readFetchIdentity(resolved, pkg);
}

function decodeComponent(text: string): string | undefined {
  try {
    return decodeURIComponent(text);
  } catch {
    return undefined;
  }
}

/** The resolution a `patch:` reference patches, or nothing for one nested deeper. */
function readPatchedResolution(reference: string): string | undefined {
  const end = reference.indexOf(PATCH_SEPARATOR);
  const encoded = reference.slice(PATCH_PROTOCOL.length, end);
  const inner = end === -1 ? undefined : decodeComponent(encoded);
  const patchedAgain = inner?.includes(`@${PATCH_PROTOCOL}`) ?? true;
  return patchedAgain ? undefined : inner;
}

/**
 * Berry fetches from `resolution` alone: a plain `npm:` reference from the
 * registry, one bound to `__archiveUrl` from that URL, a `patch:` one from
 * the resolution it patches, any other binding from no host this knows.
 */
function readBerryHost(
  readField: (field: string) => string | undefined,
  pkg: PackageKey,
): string | undefined {
  const reference = readBerryReference(readField);
  if (reference === undefined) {
    return undefined;
  }
  if (reference.startsWith(WORKSPACE_PROTOCOL)) {
    return WORKSPACE_HOST;
  }
  if (reference.startsWith(PATCH_PROTOCOL)) {
    const patched = readPatchedResolution(reference);
    const inner = patched === undefined ? undefined : splitPackageKey(patched);
    // Berry installs the patched source under the entry's name; another package's source is a swap.
    if (patched === undefined || inner?.name !== pkg.name) {
      return undefined;
    }
    return readBerryHost(() => patched, {
      name: pkg.name,
      version: inner.version,
    });
  }
  const bindingsStart = reference.indexOf(BERRY_BINDINGS_SEPARATOR);
  if (bindingsStart !== -1) {
    // Only berry's npm fetchers read `__archiveUrl`; patch, git and tarball ones ignore it.
    if (!PLAIN_NPM_REFERENCE.test(reference.slice(0, bindingsStart))) {
      return undefined;
    }
    const bindings = new URLSearchParams(
      reference.slice(bindingsStart + BERRY_BINDINGS_SEPARATOR.length),
    );
    const archiveUrl = bindings.get(BERRY_ARCHIVE_BINDING);
    return archiveUrl === null ? undefined : readFetchIdentity(archiveUrl, pkg);
  }
  return PLAIN_NPM_REFERENCE.test(reference)
    ? REGISTRY_HOST
    : readFetchIdentity(reference, pkg);
}

interface ClassicWalk {
  entries: ClassicEntry[];
  /** False after a blank line: yarn's parser stops reading an entry there, silently. */
  entryOpen: boolean;
  /** True right under a `key:` opener, the only place a 4-space line may sit. */
  inNestedBlock: boolean;
}

/** Reads one field line into `entry`; nothing when the line is not one classic yarn writes. */
function readClassicField(
  line: string,
  entry: ClassicEntry,
): ClassicFieldRead | undefined {
  const match = CLASSIC_FIELD.exec(line);
  const key = match?.[1] === undefined ? undefined : readQuoted(match[1]);
  if (match === null || key === undefined || entry.fields.has(key)) {
    return undefined;
  }
  const rawValue = match[2];
  if (rawValue === undefined) {
    return ClassicFieldReads.BLOCK;
  }
  const value = readQuoted(rawValue);
  if (value === undefined) {
    return undefined;
  }
  entry.fields.set(key, value);
  return ClassicFieldReads.VALUE;
}

function isClassicHeaderComment(line: string): boolean {
  return (
    CLASSIC_HEADER_COMMENTS.has(line) || CLASSIC_VERSION_COMMENT.test(line)
  );
}

/** Reads one line into the walk; `false` when classic yarn would not write it there. */
function readClassicLine(line: string, walk: ClassicWalk): boolean {
  if (line === "") {
    walk.entryOpen = false;
    walk.inNestedBlock = false;
    return true;
  }
  if (line.startsWith("#")) {
    const headerComment =
      walk.entries.length === 0 && isClassicHeaderComment(line);
    return headerComment;
  }
  if (line.startsWith(" ") && !walk.entryOpen) {
    return false;
  }
  if (NESTED_LINE.test(line)) {
    const nestedField = walk.inNestedBlock && NESTED_FIELD.test(line);
    return nestedField;
  }
  if (!line.startsWith(" ")) {
    walk.inNestedBlock = false;
    walk.entryOpen = true;
    const descriptors = line.endsWith(":")
      ? readClassicDescriptors(line.slice(0, -1))
      : undefined;
    if (descriptors !== undefined) {
      walk.entries.push({ descriptors, fields: new Map() });
    }
    return descriptors !== undefined;
  }

  const current = walk.entries.at(-1);
  const field =
    current === undefined ? undefined : readClassicField(line, current);
  walk.inNestedBlock = field === ClassicFieldReads.BLOCK;
  return field !== undefined;
}

function parseClassicEntries(text: string): ClassicEntry[] | undefined {
  const walk: ClassicWalk = {
    entries: [],
    entryOpen: false,
    inNestedBlock: false,
  };
  for (const line of text.split(LINE_BREAK)) {
    if (!readClassicLine(line, walk)) {
      return undefined;
    }
  }
  return walk.entries;
}

function readClassicLockfile(text: string): LockfileRead {
  const parsed = parseClassicEntries(text);
  if (parsed === undefined) {
    return failRead(LockfileReadFailures.UNPARSEABLE);
  }

  const seen = new Set<string>();
  const entries: LockfileEntry[] = [];
  for (const { descriptors, fields } of parsed) {
    const names = claimNames(descriptors, undefined, seen);
    const version = fields.get("version");
    if (names === undefined || version === undefined) {
      return failRead(LockfileReadFailures.AMBIGUOUS);
    }
    const ranges = descriptors.map(
      (descriptor) => splitPackageKey(descriptor)?.version ?? "/",
    );
    const local = ranges.some((range) => LOCAL_RANGE.test(range));
    const fetched = { name: names.fetched, version };
    // yarn 1 fetches by the descriptor itself without `resolved` or for an exotic range.
    const fetchedBy = fields.has("resolved")
      ? descriptors.filter((_, index) =>
          EXOTIC_RANGE.test(ranges[index] ?? "/"),
        )
      : descriptors;
    const readField = (field: string) => fields.get(field);
    const host = local ? undefined : readClassicHost(readField, fetched);
    const fieldSource = readSource(readField);
    const source =
      fetchedBy.length > 0
        ? `${fieldSource} ${fetchedBy.toSorted().join(", ")}`
        : fieldSource;
    for (const name of names.installed) {
      const entry = toEntry(name, version, source, host);
      if (name !== names.fetched) {
        entry.aliasOf = names.fetched;
      }
      entries.push(entry);
    }
  }
  return { ok: true, value: entries };
}

/**
 * The first line that is neither blank nor a comment. Berry writes
 * `__metadata:` there; yarn 1's own parser rejects it and falls back to
 * js-yaml, which reads the same YAML this path reads.
 */
function readFirstContentLine(text: string): string | undefined {
  let start = 0;
  while (start < text.length) {
    const newline = text.indexOf("\n", start);
    const stop = newline === -1 ? text.length : newline;
    const line = text.slice(start, stop).replace(TRAILING_CARRIAGE_RETURN, "");
    const content = line.trim() !== "" && !line.startsWith("#");
    if (content) {
      return line;
    }
    start = stop + 1;
  }
  return undefined;
}

function readBerryLockfile(text: string): LockfileRead {
  if (readFirstContentLine(text) !== METADATA_LINE) {
    return failRead(LockfileReadFailures.AMBIGUOUS);
  }
  const read = readYamlLockfile(text, BERRY_SHAPE);
  if (!read.ok) {
    return failRead(read.error);
  }
  const [document] = read.value;
  const isMap = typeof document === "object" && document !== null;
  if (!isMap) {
    return failRead(LockfileReadFailures.UNPARSEABLE);
  }

  const seen = new Set<string>();
  const entries: LockfileEntry[] = [];
  for (const [key, value] of Object.entries(document)) {
    if (key === METADATA_KEY) {
      continue;
    }
    const record = BerryEntrySchema.safeParse(value);
    // Berry never writes `resolved`; yarn 1, reading this file as YAML, fetches from it.
    if (!record.success || record.data.resolved !== undefined) {
      return failRead(LockfileReadFailures.AMBIGUOUS);
    }
    const descriptors = readBerryDescriptors(key);
    const names =
      descriptors === undefined
        ? undefined
        : claimNames(
            descriptors,
            readResolvedName(record.data.resolution),
            seen,
          );
    if (names === undefined) {
      return failRead(LockfileReadFailures.AMBIGUOUS);
    }
    const fields = new Map(Object.entries(record.data));
    const fetched = { name: names.fetched, version: record.data.version };
    const readField = (field: string) => fields.get(field);
    const host = readBerryHost(readField, fetched);
    // A workspace's folder is where it sits, not where it comes from: a move changes no source.
    const reference = readBerryReference(readField);
    const linksWorkspace = reference?.startsWith(WORKSPACE_PROTOCOL) === true;
    const source = linksWorkspace ? WORKSPACE_HOST : readSource(readField);
    for (const name of names.installed) {
      const entry = toEntry(name, record.data.version, source, host);
      if (names.fetched !== name) {
        entry.aliasOf = names.fetched;
      }
      entries.push(entry);
    }
  }
  return { ok: true, value: entries };
}

/**
 * Berry's own legacy test, `/^(#.*(\r?\n))*?#\s+yarn\s+lockfile\s+v1\r?\n/i`,
 * as a line scan: the regex overflows V8's backtrack stack on a long comment
 * block. A match goes to berry's PEG grammar, not to a YAML parser.
 */
function readsAsBerryLegacy(text: string): boolean {
  let position = 0;
  while (text.startsWith("#", position)) {
    BERRY_LEGACY_MARKER.lastIndex = position;
    if (BERRY_LEGACY_MARKER.test(text)) {
      return true;
    }
    LINE_BODY.lastIndex = position;
    LINE_BODY.test(text);
    const lineEnd = LINE_BODY.lastIndex;
    const newline = text.startsWith("\r\n", lineEnd) ? lineEnd + 1 : lineEnd;
    if (text[newline] !== "\n") {
      return false;
    }
    position = newline + 1;
  }
  return false;
}

/** Every entry of a yarn lockfile: classic by its marker comment, berry otherwise. */
export function readYarnLockfile(text: string): LockfileRead {
  const isClassic = CLASSIC_MARKER_LINE.test(
    text.slice(0, CLASSIC_MARKER_WINDOW),
  );
  if (isClassic !== readsAsBerryLegacy(text)) {
    return failRead(LockfileReadFailures.AMBIGUOUS);
  }
  if (!isClassic) {
    return readBerryLockfile(text);
  }
  if (LONE_CARRIAGE_RETURN.test(text)) {
    return failRead(LockfileReadFailures.UNPARSEABLE);
  }
  return readClassicLockfile(text);
}
