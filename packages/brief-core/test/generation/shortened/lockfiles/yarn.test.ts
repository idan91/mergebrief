import { describe, expect, it } from "vitest";
import { readYarnLockfile } from "../../../../src/generation/shortened/lockfiles/yarn";
import { summarizeTexts } from "../helpers";

const CLASSIC_BEFORE = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@scope/gone@^2.0.0":
  version "2.0.0"
  resolved "https://registry.yarnpkg.com/@scope/gone/-/gone-2.0.0.tgz"

lodash@^4.17.0:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#1"
  integrity sha512-lodash

react@^18.2.0:
  version "18.2.0"
  resolved "https://registry.yarnpkg.com/react/-/react-18.2.0.tgz#abc"
  integrity sha512-react-old
  dependencies:
    loose-envify "^1.1.0"
`;

const CLASSIC_AFTER = CLASSIC_BEFORE.replace(
  '"@scope/gone@^2.0.0":\n  version "2.0.0"\n  resolved "https://registry.yarnpkg.com/@scope/gone/-/gone-2.0.0.tgz"',
  '"left-pad@^1.3.0", left-pad@~1.3.0:\n  version "1.3.0"',
)
  .replace("lodash-4.17.21.tgz#1", "lodash-4.17.21.tgz#2")
  .replace(
    'react@^18.2.0:\n  version "18.2.0"',
    'react@^18.3.0:\n  version "18.3.1"',
  )
  .replace("react-18.2.0.tgz", "react-18.3.1.tgz");

const BERRY_BEFORE = `__metadata:
  version: 8
  cacheKey: 10c0

"@babel/core@npm:^7.0.0, @babel/core@npm:^7.12.3":
  version: 7.24.0
  resolution: "@babel/core@npm:7.24.0"
  checksum: 10c0/old
  languageName: node
  linkType: hard
`;

const COMMENT_LINES = 10_000_000;

function summarize(before: string, after: string) {
  return summarizeTexts("yarn.lock", before, after);
}

function makeBerryEntry(key: string, version: string, resolution: string) {
  return `\n"${key}":\n  version: ${version}\n  resolution: "${resolution}"\n  checksum: 10c0/x\n  languageName: node\n  linkType: hard\n`;
}

const MERGED_ALIAS_CLASSIC = `
"string-width-cjs@npm:string-width@^4.2.0", string-width@^4.1.0:
  version "4.2.3"
  resolved "https://registry.yarnpkg.com/string-width/-/string-width-4.2.3.tgz#abc"
  integrity sha512-sw
`;

const LINKED_CLASSIC = `
"internal@link:./scripts/rules":
  version "0.0.0"
  uid ""
`;

/** yarn 1 quotes neither the key nor the nested range of a `user/repo#ref` dependency. */
const SHORTHAND_CLASSIC = `
foo@acme/foo#v1.0.0:
  version "1.0.0"
  resolved "https://codeload.github.com/acme/foo/tar.gz/0123456789abcdef"
`;

/** A berry lockfile holding the root workspace and each `name@workspace:path` locator. */
function makeBerryWorkspaces(locators: string[]): string {
  const entries = ["root@workspace:.", ...locators].map(
    (locator) =>
      `"${locator}":\n  version: 0.0.0-use.local\n  resolution: "${locator}"\n  languageName: unknown\n  linkType: soft\n`,
  );
  return `__metadata:\n  version: 8\n  cacheKey: 10c0\n${entries.map((entry) => `\n${entry}`).join("")}`;
}

const REGISTRY = ["registry"];
const TOO_MANY_DESCRIPTORS = 129;
const YARN_REGISTRY = ["registry:https://registry.yarnpkg.com"];

describe("yarn lockfile merged keys and patches", () => {
  it("reads a berry key merging an alias with its target", () => {
    const after = `${BERRY_BEFORE}${makeBerryEntry(
      "string-width-cjs@npm:string-width@^4.2.0, string-width@npm:^4.1.0",
      "4.2.3",
      "string-width@npm:4.2.3",
    )}`;

    expect(summarize(BERRY_BEFORE, after)).toMatchObject({
      changes: {
        added: [
          { name: "string-width", version: "4.2.3", hosts: REGISTRY },
          {
            name: "string-width-cjs",
            version: "4.2.3",
            hosts: REGISTRY,
            aliasOf: "string-width",
          },
        ],
      },
    });
  });

  it("reads a berry key repeating one descriptor as one entry", () => {
    const after = `${BERRY_BEFORE}${makeBerryEntry(
      "p-limit@npm:^3.1.0, p-limit@npm:^3.1.0 ",
      "3.1.0",
      "p-limit@npm:3.1.0",
    )}`;

    expect(summarize(BERRY_BEFORE, after)).toMatchObject({
      changes: { added: [{ name: "p-limit", version: "3.1.0" }] },
    });
  });

  it("reads a berry key naming a package it does not alias as ambiguous", () => {
    const after = `${BERRY_BEFORE}${makeBerryEntry(
      "foo@npm:bar@^1.0.0, baz@npm:^1.0.0",
      "1.0.0",
      "bar@npm:1.0.0",
    )}`;

    expect(summarize(BERRY_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "ambiguous",
    });
  });

  it("reads a builtin patch from the registry it patches", () => {
    const after = `${BERRY_BEFORE}${makeBerryEntry(
      "typescript@patch:typescript@npm%3A^5.4.0#optional!builtin<compat/typescript>",
      "5.4.5",
      "typescript@patch:typescript@npm%3A5.4.5#optional!builtin<compat/typescript>::version=5.4.5&hash=5adc0c",
    )}`;

    expect(summarize(BERRY_BEFORE, after)).toMatchObject({
      changes: {
        added: [{ name: "typescript", version: "5.4.5", hosts: REGISTRY }],
      },
    });
  });

  it("reads a patch of another package's source as unknown host", () => {
    const after = `${BERRY_BEFORE}${makeBerryEntry(
      "lodash@patch:evil-pkg@npm%3A^4.17.21#./p.patch",
      "4.17.21",
      "lodash@patch:evil-pkg@npm%3A4.17.21#./p.patch::version=4.17.21&hash=x",
    )}`;
    const summary = summarize(BERRY_BEFORE, after);
    const [added] =
      summary !== undefined && "changes" in summary
        ? summary.changes.added
        : [];

    expect(added).toEqual({ name: "lodash", version: "4.17.21" });
  });

  it("reads a classic key merging an alias with its target", () => {
    const after = `${CLASSIC_BEFORE}${MERGED_ALIAS_CLASSIC}`;

    expect(summarize(CLASSIC_BEFORE, after)).toMatchObject({
      changes: {
        added: [
          { name: "string-width", version: "4.2.3", hosts: YARN_REGISTRY },
          {
            name: "string-width-cjs",
            version: "4.2.3",
            hosts: YARN_REGISTRY,
            aliasOf: "string-width",
          },
        ],
      },
    });
  });

  it("reads a classic key with too many descriptors as unparseable", () => {
    const key = Array.from(
      { length: TOO_MANY_DESCRIPTORS },
      (_unused, index) => `"a${index}@npm:x@^1.0.0"`,
    ).join(", ");
    const after = `${CLASSIC_BEFORE}\n${key}:\n  version "1.0.0"\n`;

    expect(summarize(CLASSIC_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "unparseable",
    });
  });

  it("reads a classic GitHub shorthand key yarn writes bare", () => {
    const after = `${CLASSIC_BEFORE.replace(
      '    loose-envify "^1.1.0"',
      '    loose-envify "^1.1.0"\n    foo acme/foo#v1.0.0',
    )}${SHORTHAND_CLASSIC}`;

    expect(summarize(CLASSIC_BEFORE, after)).toMatchObject({
      changes: {
        added: [
          {
            name: "foo",
            version: "1.0.0",
            hosts: ["https://codeload.github.com/acme/foo/tar.gz/"],
          },
        ],
      },
    });
  });

  it("reads a classic linked entry with an empty uid", () => {
    const after = `${CLASSIC_BEFORE}${LINKED_CLASSIC}`;

    expect(summarize(CLASSIC_BEFORE, after)).toMatchObject({
      changes: { added: [{ name: "internal", version: "0.0.0" }] },
    });
  });
});

describe("yarn lockfile summary", () => {
  it.each([
    ["a marker berry reads as legacy", `# Yarn lockfile v1\n${BERRY_BEFORE}`],
    ["a marker berry misses", `\n${CLASSIC_BEFORE}`],
  ])("reads a lockfile behind %s as ambiguous", (_label, after) => {
    expect(summarize(BERRY_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "ambiguous",
    });
  });

  it("reads a long comment block without throwing", () => {
    const comments = "#\n".repeat(COMMENT_LINES);

    expect(readYarnLockfile(comments)).toEqual({
      ok: false,
      error: "ambiguous",
    });
  });

  it("reads a berry entry carrying a resolved field as ambiguous", () => {
    const after = BERRY_BEFORE.replace(
      "  checksum: 10c0/old\n",
      '  checksum: 10c0/old\n  resolved: "https://attacker.example/core.tgz"\n',
    );

    expect(summarize(BERRY_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "ambiguous",
    });
  });

  it("lists added, removed, updated and same-version source changes", () => {
    expect(summarize(CLASSIC_BEFORE, CLASSIC_AFTER)).toEqual({
      format: "yarn",
      changes: {
        added: [{ name: "left-pad", version: "1.3.0" }],
        removed: [
          {
            name: "@scope/gone",
            version: "2.0.0",
            hosts: ["registry:https://registry.yarnpkg.com"],
          },
        ],
        updated: [
          {
            name: "react",
            from: "18.2.0",
            to: "18.3.1",
            fromHosts: ["registry:https://registry.yarnpkg.com"],
            toHosts: ["registry:https://registry.yarnpkg.com"],
          },
        ],
        sourceChanged: [
          {
            name: "lodash",
            version: "4.17.21",
            fromHosts: ["registry:https://registry.yarnpkg.com"],
            toHosts: ["registry:https://registry.yarnpkg.com"],
          },
        ],
      },
      baseHosts: ["registry:https://registry.yarnpkg.com"],
    });
  });

  it("reads a second entry for a kept version as a source change", () => {
    const after = `${CLASSIC_BEFORE}\nlodash@^4.17.21:\n  version "4.17.21"\n  resolved "https://mirror.example/lodash.tgz"\n`;

    expect(summarize(CLASSIC_BEFORE, after)).toMatchObject({
      changes: { sourceChanged: [{ name: "lodash", version: "4.17.21" }] },
    });
  });

  it("reads berry entries", () => {
    const after = BERRY_BEFORE.replaceAll("7.24.0", "7.25.2");

    expect(summarize(BERRY_BEFORE, after)).toMatchObject({
      changes: {
        updated: [{ name: "@babel/core", from: "7.24.0", to: "7.25.2" }],
      },
    });
  });

  it("reads berry's npm protocol as the registry host", () => {
    const after = BERRY_BEFORE.replaceAll("7.24.0", "7.25.2");

    expect(summarize(BERRY_BEFORE, after)).toMatchObject({
      changes: {
        updated: [{ fromHosts: ["registry"], toHosts: ["registry"] }],
      },
    });
  });

  it("leaves the hosts of a version with no resolved field unknown", () => {
    const summary = summarize(CLASSIC_BEFORE, CLASSIC_AFTER);

    expect(summary).toMatchObject({
      changes: { added: [{ name: "left-pad", version: "1.3.0" }] },
    });
    expect(JSON.stringify(summary)).not.toContain(
      '"left-pad","version":"1.3.0","hosts"',
    );
  });

  it("reads a new descriptor on an entry with no resolved field", () => {
    const local = CLASSIC_AFTER.replace(
      '"left-pad@^1.3.0", left-pad@~1.3.0:',
      '"left-pad@file:./vendor/left-pad":',
    );
    const remote = CLASSIC_AFTER.replace(
      '"left-pad@^1.3.0", left-pad@~1.3.0:',
      '"left-pad@https://evil.example/left-pad.tgz":',
    );

    expect(summarize(local, remote)).toMatchObject({
      changes: { sourceChanged: [{ name: "left-pad", version: "1.3.0" }] },
    });
  });

  it.each(["file:./vendor/lodash", "C:/vendor/lodash"])(
    "reads a key moved to %s behind a kept resolved field",
    (range) => {
      const local = CLASSIC_BEFORE.replace(
        "lodash@^4.17.0:",
        `"lodash@${range}":`,
      );
      const summary = summarize(CLASSIC_BEFORE, local);

      expect(summary).toMatchObject({
        changes: { sourceChanged: [{ name: "lodash", version: "4.17.21" }] },
      });
      const [change] =
        summary !== undefined && "changes" in summary
          ? summary.changes.sourceChanged
          : [];
      expect(change?.toHosts).toBeUndefined();
    },
  );

  it("reads a merged registry range as no source change", () => {
    const merged = CLASSIC_BEFORE.replace(
      "lodash@^4.17.0:",
      "lodash@^4.17.0, lodash@^4.17.20:",
    );

    expect(summarize(CLASSIC_BEFORE, merged)).toMatchObject({
      changes: { sourceChanged: [], updated: [], added: [], removed: [] },
    });
  });

  it("reads a range joining an alias-merged key as no source change", () => {
    const entry = (key: string) =>
      [
        "# yarn lockfile v1",
        "",
        `${key}:`,
        '  version "4.2.3"',
        '  resolved "https://registry.yarnpkg.com/string-width/-/string-width-4.2.3.tgz#269c"',
        "  integrity sha512-width",
        "",
      ].join("\n");
    const aliasKey =
      '"string-width-cjs@npm:string-width@^4.2.0", "string-width@^4.1.0"';

    expect(
      summarize(entry(aliasKey), entry(`${aliasKey}, "string-width@^4.2.3"`)),
    ).toMatchObject({
      changes: { sourceChanged: [], updated: [], added: [], removed: [] },
    });
  });

  it("reads a patch by its inner source, never its archive url", () => {
    const after = BERRY_BEFORE.replaceAll("7.24.0", "7.25.2").replace(
      '"@babel/core@npm:7.25.2"',
      '"@babel/core@patch:@babel/core@https%3A%2F%2Fevil.example%2Fc.tgz#./x.patch::version=7.25.2&__archiveUrl=https%3A%2F%2Fregistry.npmjs.org%2F%40babel%2Fcore%2F-%2Fcore-7.25.2.tgz"',
    );
    const summary = summarize(BERRY_BEFORE, after);
    const [update] =
      summary !== undefined && "changes" in summary
        ? summary.changes.updated
        : [];

    expect(update?.toHosts).toEqual(["https://evil.example/c.tgz"]);
  });

  it("reads a berry alias from the package its resolution names", () => {
    const berry = (target: string, version: string) =>
      [
        "__metadata:",
        "  version: 8",
        "  cacheKey: 10c0",
        "",
        `"foo@npm:${target}@^${version}":`,
        `  version: ${version}`,
        `  resolution: "${target}@npm:${version}"`,
        "  languageName: node",
        "  linkType: hard",
        "",
      ].join("\n");

    expect(
      summarize(berry("bar", "1.0.0"), berry("evil", "2.0.0")),
    ).toMatchObject({
      changes: {
        updated: [
          {
            name: "foo",
            fromAliasOf: "bar",
            toAliasOf: "evil",
            fromHosts: ["registry"],
            toHosts: ["registry"],
          },
        ],
      },
    });
  });

  it.each([
    [
      "an archive url binding",
      "@babel/core@npm:7.25.2::__archiveUrl=https%3A%2F%2Fmirror.example%2Fx.tgz",
      ["https://mirror.example/x.tgz"],
    ],
    ["another binding", "@babel/core@npm:7.25.2::__other=x", undefined],
  ])(
    "reads the berry host of a resolution with %s",
    (_label, resolution, hosts) => {
      const after = BERRY_BEFORE.replaceAll("7.24.0", "7.25.2").replace(
        '"@babel/core@npm:7.25.2"',
        JSON.stringify(resolution),
      );
      const summary = summarize(BERRY_BEFORE, after);

      expect(summary).toMatchObject({
        changes: { updated: [{ name: "@babel/core" }] },
      });
      const [update] =
        summary !== undefined && "changes" in summary
          ? summary.changes.updated
          : [];
      expect(update?.toHosts).toEqual(hosts);
    },
  );

  it("reads every berry workspace from one local host", () => {
    const before = makeBerryWorkspaces(["@scope/lib@workspace:packages/lib"]);
    const after = makeBerryWorkspaces([
      "@scope/lib@workspace:libs/lib",
      "@scope/new@workspace:packages/new",
    ]);

    expect(summarize(before, after)).toMatchObject({
      changes: {
        added: [{ name: "@scope/new", hosts: ["workspace:"] }],
        removed: [],
        updated: [],
        sourceChanged: [],
      },
      baseHosts: ["workspace:"],
    });
  });

  it("reads the same text with CRLF line endings the same way", () => {
    const crlf = CLASSIC_AFTER.replaceAll("\n", "\r\n");

    expect(summarize(CLASSIC_BEFORE, crlf)).toEqual(
      summarize(CLASSIC_BEFORE, CLASSIC_AFTER),
    );
  });

  it.each([
    [
      "a descriptor listed twice",
      CLASSIC_BEFORE,
      `${CLASSIC_BEFORE}\nlodash@^4.17.0:\n  version "4.17.21"\n`,
      "ambiguous",
    ],
    [
      "a field listed twice",
      CLASSIC_BEFORE,
      CLASSIC_BEFORE.replace(
        "  integrity sha512-lodash",
        '  integrity sha512-lodash\n  resolved "https://mirror.example/x.tgz"',
      ),
      "unparseable",
    ],
    [
      "a berry key listed twice",
      BERRY_BEFORE,
      `${BERRY_BEFORE}"@babel/core@npm:^7.0.0":\n  version: 7.24.0\n`,
      "ambiguous",
    ],
  ])("reads a lockfile with %s as unread", (_label, before, after, unread) => {
    expect(summarize(before, after)).toEqual({ format: "yarn", unread });
  });

  it("reads a classic field key holding a comma as unparseable", () => {
    const after = CLASSIC_BEFORE.replace(
      "  integrity sha512-lodash",
      '  integrity sha512-lodash\n  resolved, resolved "https://mirror.example/x.tgz"',
    );

    expect(summarize(CLASSIC_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "unparseable",
    });
  });

  it.each([
    [
      "classic",
      CLASSIC_BEFORE,
      `${CLASSIC_BEFORE}\nx@^1, lodash@^4.17.0:\n  version "1.0.0"\n`,
    ],
    [
      "berry",
      BERRY_BEFORE,
      `${BERRY_BEFORE}\n"x@npm:1,@babel/core@npm:^7.0.0":\n  version: 1.0.0\n`,
    ],
  ])(
    "reads a %s key claiming a descriptor twice as ambiguous",
    (_label, before, after) => {
      expect(summarize(before, after)).toEqual({
        format: "yarn",
        unread: "ambiguous",
      });
    },
  );

  it("reads a classic lockfile with a lone carriage return as unparseable", () => {
    const after = CLASSIC_BEFORE.replace(
      '    loose-envify "^1.1.0"',
      '    loose-envify "^1.1.0"\r"lodash@^4.17.0":',
    );

    expect(summarize(CLASSIC_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "unparseable",
    });
  });

  it("reads a nested classic line yarn never writes as unparseable", () => {
    const after = CLASSIC_BEFORE.replace(
      '    loose-envify "^1.1.0"',
      '    loose-envify "^1.1.0" extra',
    );

    expect(summarize(CLASSIC_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "unparseable",
    });
  });

  it("reads a berry file with a lone carriage return as unparseable", () => {
    const after = BERRY_BEFORE.replace(
      "  linkType: hard",
      '  linkType: hard #\r  resolution: "@babel/core@https://mirror.example/x.tgz"',
    );

    expect(summarize(BERRY_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "unparseable",
    });
  });

  it("reads a berry file that does not open on its metadata as ambiguous", () => {
    const after = `"@babel/core@npm:^7.0.0":\n  version: 7.24.0\n\n${BERRY_BEFORE.split("\n\n")[0]}\n`;

    expect(summarize(BERRY_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "ambiguous",
    });
  });

  it("reads a marker of another lockfile version as no classic marker", () => {
    const after = CLASSIC_BEFORE.replace(
      "# yarn lockfile v1",
      "# yarn lockfile v10",
    );

    expect(summarize(CLASSIC_BEFORE, after)).toMatchObject({
      unread: expect.any(String),
    });
  });

  it("reads a yarn lockfile with no classic marker or metadata as ambiguous", () => {
    const after =
      '"lodash@^4.17.0":\n  version: "4.17.21"\n  resolved: "https://mirror.example/x.tgz"\n';

    expect(summarize(CLASSIC_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "ambiguous",
    });
  });

  it.each([
    ["a token yarn would quote", '    loose-envify "^1.1.0"', "    'x y"],
    [
      "a trailing comment",
      '    loose-envify "^1.1.0"',
      '    loose-envify "^1.1.0" #x',
    ],
    ["a bare number", '  version "18.2.0"', "  version 18.2.0"],
    [
      "an escape in a quoted token",
      '  version "18.2.0"',
      '  version "18.2.0\\\\"',
    ],
    ["a whitespace-only line", "\nreact@^18.2.0:", "\n  \nreact@^18.2.0:"],
    [
      "a blank line inside an entry",
      '  version "4.17.21"\n',
      '  version "4.17.21"\n\n',
    ],
    [
      "a comment inside an entry",
      '  version "4.17.21"\n',
      '  version "4.17.21"\n# x\n',
    ],
    [
      "a second lockfile version comment",
      "# yarn lockfile v1\n",
      "# yarn lockfile v2\n# yarn lockfile v1\n",
    ],
    ["an empty quoted key", '    loose-envify "^1.1.0"', '    "" "^1.1.0"'],
    [
      "a control character in a quoted token",
      '    loose-envify "^1.1.0"',
      '    loose-envify "^1.1.0\t"',
    ],
    [
      "a tab between descriptors",
      '"left-pad@^1.3.0", left-pad@~1.3.0:',
      '"left-pad@^1.3.0",\tleft-pad@~1.3.0:',
    ],
  ])("reads a classic file with %s as unparseable", (_label, from, to) => {
    const base = CLASSIC_AFTER.includes(from) ? CLASSIC_AFTER : CLASSIC_BEFORE;
    const after = base.replace(from, to);

    expect(after).not.toBe(base);
    expect(summarize(CLASSIC_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "unparseable",
    });
  });

  it("reads a classic line in a place yarn never writes as unparseable", () => {
    const after = CLASSIC_BEFORE.replace(
      "  integrity sha512-lodash",
      '  integrity sha512-lodash\n    resolved "https://mirror.example/x.tgz"',
    );

    expect(summarize(CLASSIC_BEFORE, after)).toEqual({
      format: "yarn",
      unread: "unparseable",
    });
  });
});
