import { renderElkjsSources } from "./elkjs";
import {
  GITHUB_ORIGIN,
  LICENSE_TEXTS,
  RECORDED_LIBVIPS_VERSION_LABEL,
  REGENERATE_COMMAND,
  SHARP_LIBVIPS_REPOSITORY,
  THIRD_PARTY_NOTICES_FILE,
} from "./consts";
import type { SourceDownload } from "./types";

function formatRow(download: SourceDownload): string {
  return `| ${download.library} | ${download.version ?? "patch"} | ${download.url} |`;
}

/** `SOURCES.md`: per component, the recorded version, how it ships, and every upstream download. */
export function renderSourcesFile(
  version: string,
  downloads: readonly SourceDownload[],
  elkjsVersion: string | undefined,
): string {
  const release = `${GITHUB_ORIGIN}/${SHARP_LIBVIPS_REPOSITORY}/tree/v${version}`;
  const texts = LICENSE_TEXTS.map((text) => text.fileName).join(", ");
  const libvips = [
    "# Sources of the bundled third-party code",
    "",
    `Generated by \`${REGENERATE_COMMAND}\`; do not edit by hand.`,
    "",
    "## libvips",
    "",
    `${RECORDED_LIBVIPS_VERSION_LABEL} ${version}`,
    "",
    `The image runs sharp with its prebuilt libvips, the npm package \`@img/sharp-libvips-<platform>@${version}\`, unmodified. Its libraries load as separate shared objects from that package's \`lib/\` folder under \`/app/node_modules/.pnpm/\`, so a build of your own with the same interface can replace them.`,
    "",
    `${THIRD_PARTY_NOTICES_FILE} lists each library and its licence; ${texts} hold the full texts. Each library's source is the upstream download below, the one the release's build fetched, followed by any patch it applied. The build itself is ${release} (\`build/posix.sh\`, versions pinned in \`versions.properties\`).`,
    "",
    "| Library | Version | Source |",
    "| --- | --- | --- |",
    ...downloads.map(formatRow),
    "",
  ].join("\n");
  if (elkjsVersion === undefined) {
    return libvips;
  }
  return `${libvips}\n${renderElkjsSources(elkjsVersion)}`;
}
